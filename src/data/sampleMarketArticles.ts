/** 예시 뉴스 → 본문을 붙인 기사 (본문이 없으면 null) */
export function toSampleArticle(item: { title: string; source?: string; type?: string; category?: string }) {
  const body = SAMPLE_MARKET_ARTICLES[item.title];
  if (!body) return null;
  return {
    title: item.title,
    originalTitle: '',
    summary: body.summary,
    content: body.content,
    category: item.type || item.category || '중국증시',
    url: '',
    source: item.source || '예시',
    publishedAt: new Date().toISOString(),
    isSample: true,
  };
}
