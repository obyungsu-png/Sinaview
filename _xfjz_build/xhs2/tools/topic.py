"""학법 감점 법규학습은행 주제 분류(8개) — 중국어 문제·보기 글 규칙"""
import re
EMERG = r'爆胎|爆裂|失控|失灵|失效|着火|起火|自燃|燃烧|灭火|落水|急救|伤员|受伤|报警|倾翻|翻车|泄漏|熄火|撞击护栏|碰撞护栏|避险车道|快处快赔|自行协商|发生(交通)?事故|事故(现场|处理|责任)|单方交通事故|救援'
CASE = re.compile(r'[一-鿿]某')
def topic(q, opts=()):
    t = q + ' ' + ' '.join(opts)
    if CASE.search(q) and re.search(r'违法行为|违法|事故', q):
        return 7  # 사고 사례
    if re.search(r'学法减分|满分教育|满分学习|累积记分达到12|累计记分达到|记分达到12|满分记录', t):
        return 1
    if re.search(r'记\s*\d+\s*分|记几分|记多少分|扣多少分|一次记|记分', t):
        return 2
    if re.search(r'驾驶证|准驾|实习期|换证|补领|换领|审验|体检|申请|有效期|增驾|检验|注册登记|登记证书|驾照|报名', t):
        return 4
    if re.search(r'罚款|拘留|吊销|处罚|刑事责任|追究|收缴|扣留|扣押|交通肇事罪|犯罪|强制', t):
        return 3
    if re.search(EMERG, t):
        return 7
    if re.search(r'高速公路|快速路|匝道|应急车道|加速车道|减速车道|收费', t):
        return 5
    if re.search(r'最高速度|最高车速|最低车速|限速|时速|公里/小时|车速不得|车速不能', t):
        return 5
    if re.search(r'灯|标志|标线|信号|手势|远光|近光|雾灯|示廓|夜间|仪表|网状线|导向箭头|车道线|中心线|分界线|停车让行线', t):
        return 6
    return 8
